/**
 * Measure every speaker in the fast model, so the library is labelled from
 * data rather than guesses.
 *
 *   node tools/voices/measure.js
 *
 * Each speaker says the same sentence. From it: mean pitch (which sets the
 * voice's register and the gender label), speaking rate, and loudness (for
 * normalising later). Writes packages/cadence/src/data/libritts-speakers.js, a
 * module rather than JSON so it imports the same way in Node and the bundler.
 */

import { readFile, writeFile } from 'node:fs/promises';
import * as ort from 'onnxruntime-node';
import { estimatePitch } from '../../packages/cadence/src/dsp.js';
import { loadPiper } from '../../packages/cadence/src/piper.js';

const MODEL = new URL('../../.cache/models/en_US-libritts_r-medium', import.meta.url).href;
const SENTENCE = 'The quick brown fox jumps over the lazy dog, and then it runs away.';
const WORDS = SENTENCE.split(/\s+/).length;
const OUT = new URL('../../packages/cadence/src/data/libritts-speakers.js', import.meta.url);

const config = JSON.parse(await readFile(new URL(`${MODEL}.onnx.json`), 'utf8'));
const piper = await loadPiper({ ort, model: await readFile(new URL(`${MODEL}.onnx`)), config });
const readers = Object.fromEntries(Object.entries(config.speaker_id_map).map(([reader, i]) => [i, reader]));

const speakers = [];
const start = performance.now();
for (let s = 0; s < config.num_speakers; s++) {
  const audio = await piper.speak(SENTENCE, { speaker: s });
  // Voiced length only: leading and trailing silence says nothing about pace.
  let a = 0;
  let b = audio.length - 1;
  while (a < b && Math.abs(audio[a]) < 0.01) a++;
  while (b > a && Math.abs(audio[b]) < 0.01) b--;
  const seconds = (b - a) / piper.sampleRate;
  let sum = 0;
  for (let i = a; i < b; i++) sum += audio[i] * audio[i];
  speakers.push({
    speaker: s,
    reader: readers[s],
    pitch: estimatePitch(audio, piper.sampleRate),
    wordsPerMinute: Math.round((WORDS / seconds) * 60),
    rmsDb: +(10 * Math.log10(sum / Math.max(1, b - a))).toFixed(1),
  });
  if (s % 50 === 49) console.log(`  ${s + 1}/${config.num_speakers} · ${((performance.now() - start) / 1000).toFixed(0)} s`);
}

const rows = speakers.map((s) => `  ${JSON.stringify(s)},`).join('\n');
await writeFile(OUT, `/**
 * Every speaker in Piper LibriTTS-R medium, measured saying:
 * "${SENTENCE}"
 * Generated by tools/voices/measure.js. Do not edit by hand.
 */

/** @type {{speaker: number, reader: string, pitch: number, wordsPerMinute: number, rmsDb: number}[]} */
export const SPEAKERS = [
${rows}
];
`);
console.log(`Measured ${speakers.length} speakers.`);
